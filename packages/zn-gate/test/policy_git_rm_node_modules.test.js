'use strict';

// Ordinary project work stays allowed under the hook policy: removing a node_modules folder inside the project, and
// git add / git commit. git filter-branch is a history rewrite; it is expected to be blocked, and is marked todo while
// the policy does not cover it.

process.env.ZN_STATS = 'off';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');

const adapter = require('../lib/agents/claude-code');
const runner = require('../lib/hooks/runner');
const policy = require('../lib/hooks/policy');
const { checkCommand } = require('../lib/destructive');
const { createFakeVault } = require('./helpers/fake_vault');
const fakeEngine = require('./helpers/fake_engine');
const { tempDir } = require('./helpers/tmp');

function preTool(command, cwd) {
  return { session_id: 'abc123', cwd, permission_mode: 'default', hook_event_name: 'PreToolUse', tool_name: 'Bash', tool_input: { command }, tool_use_id: 'toolu_01' };
}
function run(raw, extra = {}) {
  return runner.handle(adapter, raw, { engine: fakeEngine, vault: createFakeVault(), failMode: 'open', ...extra });
}

function projectWithDeps(t) {
  const dir = tempDir(t, 'zn-proj-');
  fs.mkdirSync(path.join(dir, '.git'));
  fs.mkdirSync(path.join(dir, 'node_modules', 'left-pad'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'node_modules', 'left-pad', 'index.js'), 'module.exports = 1;\n');
  fs.writeFileSync(path.join(dir, 'src.js'), 'console.log(1);\n');
  return dir;
}

test('removing node_modules inside the project is allowed', async (t) => {
  const dir = projectWithDeps(t);
  const home = tempDir(t, 'zn-home-');
  for (const c of ['rm -rf node_modules', 'rm -r node_modules', 'rm -rf ./node_modules', 'rm -rf node_modules dist']) {
    assert.equal(checkCommand(c).verdict, 'allow', c);
    assert.equal(policy.bashDenial(c, { cwd: dir, home }), null, c);
    assert.equal((await run(preTool(c, dir), { home })).output, null, c);
  }
});

test('git add and git commit are allowed', async (t) => {
  const dir = projectWithDeps(t);
  const home = tempDir(t, 'zn-home-');
  for (const c of ['git add .', 'git add src.js', 'git commit -m "tidy the entry point"']) {
    assert.equal(checkCommand(c).verdict, 'allow', c);
    assert.equal(policy.bashDenial(c, { cwd: dir, home }), null, c);
    assert.equal((await run(preTool(c, dir), { home })).output, null, c);
  }
});

test('git filter-branch, a history rewrite, is blocked by the policy', { todo: 'gap: no rule in lib/hooks/policy.js or lib/destructive.js names git filter-branch; it is allowed today' }, async (t) => {
  const dir = projectWithDeps(t);
  const home = tempDir(t, 'zn-home-');
  const c = 'git filter-branch --force --tree-filter "rm -f secrets.txt" HEAD';
  assert.notEqual(policy.bashDenial(c, { cwd: dir, home }), null, c);
  assert.equal(checkCommand(c).verdict, 'block', c);
});
